const tex = String.raw

const PROOF = [
  'Assume the trajectory is bounded. Then only finitely many cells are visited, and some of them are visited infinitely often. Call *S* the set of those cells. The others are visited only finitely many times: after some step, the ant never leaves *S*.',
  'Pick in *S* the rightmost cell, and among those the highest one; call it *c*. Its right neighbour and its upper neighbour are not in *S*.',
  'At each visit the ant flips *c*, so it alternately turns right and left there.',
  '*If c is always entered horizontally*, the ant cannot come from the right, since the right neighbour is not in *S*. So it always arrives moving right. Turning left it leaves upwards; turning right, downwards. Every other visit, it therefore moves to the cell above, outside *S*.',
  '*If c is always entered vertically*, the ant cannot come from above. So it always arrives moving up, and every other visit, turning right, it moves to the cell on the right, outside *S*.',
  'Either way, the ant leaves *S* infinitely often, which contradicts the choice of *S*. The trajectory is never bounded.',
]

