// 123000 → « ×1,23 · 10⁵ »
const EXPOSANTS = '⁰¹²³⁴⁵⁶⁷⁸⁹'
function zoomTexte(z, langue) {
  if (z < 1e4) return `×${z.toLocaleString(langue, { maximumSignificantDigits: 3 })}`
  const e = Math.floor(Math.log10(z))
  const m = z / 10 ** e
  const sup = String(e).split('').map((c) => EXPOSANTS[Number(c)]).join('')
  return `×${m.toLocaleString(langue, { maximumFractionDigits: 1 })} · 10${sup}`
}

